VideoTranscoder::VideoTranscoder(Core *core) : mCore(core) {
    mPreparationRunning = true;
    mPreparationWorker = std::thread(&VideoTranscoder::RunPreparationWorker, this);
}

VideoTranscoder::~VideoTranscoder() {
    mPreparationRunning = false;
    mPreparationCv.notify_all();
    if (mPreparationWorker.joinable())
        mPreparationWorker.join();
}

bool VideoTranscoder::IsPrepared(const std::string &blobHash, const Options &options) {
    if (blobHash.empty())
        return false;
    Segments unused;
    return ReadExistingSegments(GetSegmentCacheDir(blobHash, options), &unused);
}

bool VideoTranscoder::NeedsPreparation(const std::string &blobHash, const Options &options) {
    if (blobHash.empty())
        return false;
    if (IsPrepared(blobHash, options))
        return false;

    const std::string key = GetSegmentCacheDir(blobHash, options).string();
    std::lock_guard<std::mutex> lock(mPreparationMutex);
    return !mPreparing.contains(key) && !mUnusable.contains(key);
}

void VideoTranscoder::RequestPreparation(int64_t assetId, const std::string &blobHash,
                                         std::vector<unsigned char> video) {
    if (blobHash.empty() || video.empty())
        return;

    const std::filesystem::path cacheDir = GetSegmentCacheDir(blobHash, OptionsFromRegistry());

    Segments unused;
    if (ReadExistingSegments(cacheDir, &unused))
        return;

    {
        std::lock_guard<std::mutex> lock(mPreparationMutex);
        if (mUnusable.contains(cacheDir.string()))
            return;
        if (!mPreparing.insert(cacheDir.string()).second)
            return; // already queued or in flight
        mPreparationQueue.push_back({assetId, cacheDir, std::move(video)});
    }
    Out("VideoTranscoder", "queued asset {} for background preparation", assetId);
    mPreparationCv.notify_one();
}

void VideoTranscoder::RunPreparationWorker() {
    while (mPreparationRunning) {
        PendingPreparation job;
        {
            std::unique_lock<std::mutex> lock(mPreparationMutex);
            mPreparationCv.wait(lock, [&] { return !mPreparationRunning || !mPreparationQueue.empty(); });
            if (!mPreparationRunning)
                break;
            job = std::move(mPreparationQueue.front());
            mPreparationQueue.pop_front();
        }

        Segments segments;
        const Response result = Segment(job.Video, OptionsFromRegistry(), job.CacheDir, &segments);
        if (result == Response::Success)
            Out("VideoTranscoder", "asset {} is ready to stream", job.AssetId);
        else
            Out("VideoTranscoder", "preparing asset {} failed: {}", job.AssetId, ResponseToString(result));

        std::lock_guard<std::mutex> lock(mPreparationMutex);
        mPreparing.erase(job.CacheDir.string());
        // A failure leaves the cache directory empty, which reads exactly like "never tried". Remember
        // it, or every request for a video ffmpeg cannot handle queues another full re-encode of it.
        if (result != Response::Success)
            mUnusable.insert(job.CacheDir.string());
    }
}

const char *VideoTranscoder::ResponseToString(Response response) {
    switch (response) {
    case Response::Success:        return "Success";
    case Response::Disabled:       return "Disabled";
    case Response::NoEncoder:      return "NoEncoder";
    case Response::EmptyInput:     return "EmptyInput";
    case Response::TempFileFailed: return "TempFileFailed";
    case Response::ProbeFailed:    return "ProbeFailed";
    case Response::EncodeFailed:   return "EncodeFailed";
    case Response::OutputMissing:  return "OutputMissing";
    case Response::BadPlaylist:    return "BadPlaylist";
    }
    return "Unknown";
}

bool VideoTranscoder::IsEngineReadable(const Probe &probe) {
    if (!probe.Ok)
        return false;
    /* H.264 only, deliberately. WebmInputFormat exists in the engine but its registration is behind
     * DFFlag VideoRegisterNewWebm, and a WebM upload was observed to play nothing at all rather than
     * fail loudly -- so VP8/VP9 are NOT treated as directly playable and get re-encoded like anything
     * else. Mp4InputFormat is the one demuxer we have evidence works, so H.264/AAC in MP4 is the only
     * combination allowed to skip the encode. */
    const bool video = probe.VideoCodec == "h264";
    const bool audio = probe.AudioCodec.empty() || probe.AudioCodec == "aac" || probe.AudioCodec == "mp3";
    return video && audio;
}

void VideoTranscoder::ResolveTools() {
    std::lock_guard<std::mutex> lock(mResolveMutex);
    if (mResolved)
        return;
    mResolved = true;

    auto configured = mCore->GetRegistry()->GetKeyValue<std::string>("emu.video.ffmpeg_path")
                          .value_or(std::string {});
    if (!configured.empty()) {
        std::filesystem::path path(configured);
        // Accept either the executable itself or the directory holding it.
        std::error_code ec;
        if (std::filesystem::is_directory(path, ec)) {
            if (LooksExecutable(path / kFfmpegExeName))  mFfmpeg  = path / kFfmpegExeName;
            if (LooksExecutable(path / kFfprobeExeName)) mFfprobe = path / kFfprobeExeName;
        } else if (LooksExecutable(path)) {
            mFfmpeg = path;
            const std::filesystem::path sibling = path.parent_path() / kFfprobeExeName;
            if (LooksExecutable(sibling))
                mFfprobe = sibling;
        }
    }

    // Bundled next to the program, which is where packaging puts it.
    if (mFfmpeg.empty()) {
        const std::filesystem::path installed = mCore->GetInstallDataDir() / kFfmpegExeName;
        if (LooksExecutable(installed))
            mFfmpeg = installed;
    }
    if (mFfprobe.empty()) {
        const std::filesystem::path installed = mCore->GetInstallDataDir() / kFfprobeExeName;
        if (LooksExecutable(installed))
            mFfprobe = installed;
    }

    // Otherwise trust PATH and let the process spawn fail if it isn't really there.
    if (mFfmpeg.empty())
        mFfmpeg = kFfmpegExeName;
    if (mFfprobe.empty())
        mFfprobe = kFfprobeExeName;

    Out("VideoTranscoder", "ffmpeg=\"{}\" ffprobe=\"{}\"", mFfmpeg.string(), mFfprobe.string());
}

