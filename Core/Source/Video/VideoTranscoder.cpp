bool WriteWholeFile(const std::filesystem::path &path, const std::vector<unsigned char> &data) {
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    if (out.fail())
        return false;
    if (!data.empty())
        out.write(reinterpret_cast<const char*>(data.data()), static_cast<std::streamsize>(data.size()));
    return out.good();
}

bool ReadWholeFile(const std::filesystem::path &path, std::vector<unsigned char> *data) {
    std::error_code ec;
    const auto size = std::filesystem::file_size(path, ec);
    if (ec)
        return false;

    std::ifstream in(path, std::ios::binary);
    if (in.fail())
        return false;

    data->resize(static_cast<size_t>(size));
    if (size == 0)
        return true;
    return static_cast<bool>(in.read(reinterpret_cast<char*>(data->data()),
                                     static_cast<std::streamsize>(size)));
}

// Quote one argv entry for the platform's command line. Windows parses the whole line in the child, so
// paths with spaces have to be quoted here; ffmpeg filter arguments carry commas and colons, which is
// exactly what breaks when a path is left bare.
std::string QuoteArg(const std::string &arg) {
#if defined(_WIN32)
    std::string out = "\"";
    size_t backslashes = 0;
    for (char c : arg) {
        if (c == '\\') {
            backslashes++;
            out += c;
            continue;
        }
        if (c == '"') {
            // Any run of backslashes immediately before a quote has to be doubled.
            out.append(backslashes, '\\');
            out += "\\\"";
        } else {
            out += c;
        }
        backslashes = 0;
    }
    out.append(backslashes, '\\'); // ...and again if the run ends the argument
    out += '"';
    return out;
#else
    std::string out = "'";
    for (char c : arg) {
        if (c == '\'')
            out += "'\\''";
        else
            out += c;
    }
    out += '\'';
    return out;
#endif
}

std::string BuildCommandLine(const std::filesystem::path &exe, const std::vector<std::string> &args) {
    std::string line = QuoteArg(exe.string());
    for (const std::string &arg : args)
        line += " " + QuoteArg(arg);
    return line;
}

// Runs a child to completion with stdout+stderr redirected into logPath, and reports its exit code.
// Redirecting to a file rather than a pipe is deliberate: a pipe that fills while nobody drains it
// deadlocks the child, and ffmpeg is extremely chatty on stderr.
bool RunProcess(const std::filesystem::path &exe, const std::vector<std::string> &args,
                const std::filesystem::path &logPath, int *exitCode) {
    const std::string commandLine = BuildCommandLine(exe, args);

#if defined(_WIN32)
    SECURITY_ATTRIBUTES sa {};
    sa.nLength = sizeof(sa);
    sa.bInheritHandle = TRUE;

    HANDLE log = CreateFileW(logPath.wstring().c_str(), GENERIC_WRITE, FILE_SHARE_READ, &sa,
                             CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (log == INVALID_HANDLE_VALUE)
        return false;

    STARTUPINFOW si {};
    si.cb = sizeof(si);
    si.dwFlags = STARTF_USESTDHANDLES;
    si.hStdInput  = nullptr;
    si.hStdOutput = log;
    si.hStdError  = log;

    PROCESS_INFORMATION pi {};

    // CreateProcessW may write to the command-line buffer, so it cannot share a literal's storage.
    std::wstring wide;
    {
        const int needed = MultiByteToWideChar(CP_UTF8, 0, commandLine.c_str(), -1, nullptr, 0);
        wide.resize(needed > 0 ? needed : 1);
        if (needed > 0)
            MultiByteToWideChar(CP_UTF8, 0, commandLine.c_str(), -1, wide.data(), needed);
    }

    // CREATE_NO_WINDOW: QtGui is a windowed application and must not flash a console per transcode.
    const BOOL ok = CreateProcessW(nullptr, wide.data(), nullptr, nullptr, TRUE,
                                   CREATE_NO_WINDOW, nullptr, nullptr, &si, &pi);
    CloseHandle(log);
    if (!ok)
        return false;

    WaitForSingleObject(pi.hProcess, INFINITE);
    DWORD code = 1;
    GetExitCodeProcess(pi.hProcess, &code);
    CloseHandle(pi.hProcess);
    CloseHandle(pi.hThread);

    *exitCode = static_cast<int>(code);
    return true;
#else
    const std::string full = commandLine + " > " + QuoteArg(logPath.string()) + " 2>&1";
    const int status = std::system(full.c_str());
    if (status == -1)
        return false;
    *exitCode = WIFEXITED(status) ? WEXITSTATUS(status) : 1;
    return true;
#endif
}

// The tail of ffmpeg's log, which is where it says why it gave up.
std::string LogTail(const std::filesystem::path &logPath, size_t maxBytes = 600) {
    std::vector<unsigned char> data;
    if (!ReadWholeFile(logPath, &data) || data.empty())
        return "";
    const size_t start = data.size() > maxBytes ? data.size() - maxBytes : 0;
    std::string tail(reinterpret_cast<const char*>(data.data()) + start, data.size() - start);
    std::replace(tail.begin(), tail.end(), '\r', ' ');
    std::replace(tail.begin(), tail.end(), '\n', ' ');
    return tail;
}

bool LooksExecutable(const std::filesystem::path &path) {
    std::error_code ec;
    return !path.empty() && std::filesystem::is_regular_file(path, ec);
}

/* True when a segment carries an H.264 sequence parameter set near its start, i.e. it can be decoded
 * without having seen an earlier segment.
 *
 * MPEG-TS has no container-level extradata, so the only place a decoder can get SPS/PPS is in-band. A
 * segment without them decodes only if playback happens to have arrived from the segment before, which
 * makes it invisible during ordinary start-at-zero playback and fatal on a seek. It happens when a
 * stream copy splits an open-GOP source: ffmpeg's TS muxer re-injects parameter sets only ahead of a
 * type-5 IDR, and an open GOP's random-access point is a plain slice carrying an SEI recovery_point.
 *
 * Scans for an Annex-B start code whose NAL header has type 7. A parameter set that is not in the
 * first chunk of the segment is no use for starting there, so a bounded scan is the right test. */
bool SegmentCanSelfStart(const std::filesystem::path &path) {
    std::ifstream in(path, std::ios::binary);
    if (in.fail())
        return false;

    constexpr size_t kScanBytes = 96 * 1024;
    std::vector<unsigned char> buf(kScanBytes);
    in.read(reinterpret_cast<char*>(buf.data()), static_cast<std::streamsize>(buf.size()));
    const size_t got = static_cast<size_t>(in.gcount());
    if (got < 5)
        return false;

    for (size_t i = 0; i + 4 < got; i++) {
        const bool startCode = buf[i] == 0 && buf[i + 1] == 0
                            && ((buf[i + 2] == 1) || (buf[i + 2] == 0 && buf[i + 3] == 1));
        if (!startCode)
            continue;
        const size_t nal = (buf[i + 2] == 1) ? i + 3 : i + 4;
        if (nal < got && (buf[nal] & 0x1F) == 7)
            return true;
    }
    return false;
}

// Segment names sort seg2 before seg10, which alphabetical order would get wrong.
bool SegmentNameLess(const std::string &a, const std::string &b) {
    if (a.size() != b.size())
        return a.size() < b.size();
    return a < b;
}

// HLSParser::parse rejects anything whose first line is not exactly "#EXTM3U" -- it compares the line
// length against 7 before it compares the bytes, so a BOM or trailing text on line one is fatal. It is
// worth catching that here rather than letting the engine fail with an opaque video error.
//
// Also rejects absolute segment URIs: those would be resolved as-is instead of against the playlist's
// own URL, which breaks the moment the playlist is served through a proxy layer from a remote host.
bool PlaylistIsAcceptable(const std::vector<unsigned char> &data, std::string *why) {
    if (data.size() < 7) {
        *why = "playlist is too short";
        return false;
    }
    if (std::string(reinterpret_cast<const char*>(data.data()), 7) != "#EXTM3U") {
        *why = "playlist does not begin with #EXTM3U";
        return false;
    }

    const std::string text(reinterpret_cast<const char*>(data.data()), data.size());
    size_t pos = 0;
    while (pos < text.size()) {
        size_t end = text.find('\n', pos);
        if (end == std::string::npos)
            end = text.size();
        std::string line = text.substr(pos, end - pos);
        pos = end + 1;

        if (!line.empty() && line.back() == '\r')
            line.pop_back();
        if (line.empty() || line[0] == '#')
            continue;

        /* A URI line. What must never appear is a URI carrying a HOST -- "https://cdn/seg0.ts" or the
         * protocol-relative "//cdn/seg0.ts" -- because that pins the segments to one machine and breaks
         * the moment the playlist is served to a client through a proxy layer from a remote host.
         *
         * An absolute PATH ("/video/v1/.../seg0.ts") is a different thing and is fine: it resolves
         * against whichever host served the playlist, which is exactly the routing we want. VideoHandler
         * rewrites the relative names ffmpeg emits into that form when it serves the playlist. */
        if (line.starts_with("//") || line.find("://") != std::string::npos) {
            *why = "playlist contains the host-qualified URI \"" + line + "\"";
            return false;
        }
    }
    return true;
}

