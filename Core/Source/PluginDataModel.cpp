std::string NormalizePath(std::string path) {
    std::replace(path.begin(), path.end(), '\\', '/');
    std::vector<std::string> parts;
    std::stringstream stream(path);
    std::string part;
    while (std::getline(stream, part, '/')) {
        if (part.empty() || part == ".")
            continue;
        if (part == "..") {
            if (parts.empty())
                return {};
            parts.pop_back();
            continue;
        }
        parts.push_back(part);
    }

    std::string result = "/";
    for (std::size_t i = 0; i < parts.size(); i++) {
        result += parts[i];
        if (i + 1 < parts.size())
            result += '/';
    }
    return result;
}

std::string JoinPath(const std::string &parent, const std::string &child) {
    if (child.starts_with('/'))
        return NormalizePath(child);
    return NormalizePath(parent + "/" + child);
}

std::string ParentPath(const std::string &path) {
    std::string normalized = NormalizePath(path);
    std::size_t slash = normalized.find_last_of('/');
    return slash == 0 ? "/" : normalized.substr(0, slash);
}

std::string FileName(const std::string &path) {
    std::string normalized = NormalizePath(path);
    std::size_t slash = normalized.find_last_of('/');
    return normalized.substr(slash + 1);
}

bool EndsWithInsensitive(const std::string &value, std::string_view suffix) {
    if (value.size() < suffix.size())
        return false;
    auto offset = value.size() - suffix.size();
    for (std::size_t i = 0; i < suffix.size(); i++) {
        if (std::tolower(static_cast<unsigned char>(value[offset + i])) !=
            std::tolower(static_cast<unsigned char>(suffix[i]))) {
            return false;
        }
    }
    return true;
}

std::string StripSuffix(const std::string &value, std::string_view suffix) {
    return value.substr(0, value.size() - suffix.size());
}

std::string UrlEncode(std::string_view value) {
    std::ostringstream stream;
    stream << std::uppercase << std::hex;
    for (unsigned char character : value) {
        if (std::isalnum(character) || character == '-' || character == '_' ||
            character == '.' || character == '~') {
            stream << character;
        } else {
            stream << '%' << std::setw(2) << std::setfill('0') << static_cast<int>(character);
        }
    }
    return stream.str();
}

std::string LuaLongString(const std::string &value) {
    std::string equals;
    while (value.find("]" + equals + "]") != std::string::npos ||
           value.ends_with("]" + equals)) {
        equals += '=';
    }
    return "[" + equals + "[" + value + "]" + equals + "]";
}

json VectorValue(const pugi::xml_node &node, std::string_view kind,
                 std::initializer_list<const char *> fields) {
    json values = json::array();
    for (const char *field : fields)
        values.push_back(node.child(field).text().as_double());
    return json {{std::string(kind), std::move(values)}};
}

