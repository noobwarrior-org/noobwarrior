std::optional<json> NoobWarrior::XmlPropertyValue(const Roblox::Property &property,
                                                  const std::string &referentNamespace,
                                                  std::string &propertyName,
                                                  std::string *unsupportedToken) {
    pugi::xml_document document;
    pugi::xml_parse_result parsed = document.load_buffer(
        property.RawBuffer.data(), property.RawBuffer.size(),
        pugi::parse_default | pugi::parse_fragment);
    pugi::xml_node node = document.first_child();
    if (!parsed || node.type() != pugi::node_element)
        return std::nullopt;

    propertyName = property.Name;
    const std::string_view token = node.name();
    if (IsSerializedOnlyProperty(propertyName)) {
        return std::nullopt;
    }
    // No serialized name is rewritten here. Every one of these renames turned a name the format
    // actually stores into its scripting alias, which invents a second column on the class. size,
    // shape, Color3uint8, MaterialVariantSerialized and Health_XML are the names files hold; Size,
    // Shape, Color, MaterialVariant and Health are what a script sees.
    if (token == "string")
        return node.text().as_string();
    if (token == "ProtectedString") {
        // Tagged, or it comes back PropertyType::String and a Script mounted into a place with
        // none writes Source as String(1) where the engine declares ProtectedString(29).
        return json {{"ProtectedString", node.text().as_string()}};
    }
    if (token == "bool")
        return node.text().as_bool();
    // Every numeric token is tagged. A bare JSON number carries no width of its own, so the
    // materializer has to guess one, and a guess is only ever safe for a value a plugin author
    // typed into a .meta.json by hand -- not for one this function read out of a file that
    // already said which element it was.
    if (token == "int") {
        try {
            return json {{"Int", std::stoll(node.text().as_string())}};
        } catch (...) {
            return std::nullopt;
        }
    }
    if (token == "int64") {
        // Tagged, because an untagged JSON number is typed by integrality on the way back in and
        // <int64> would land as PropertyType::Int -- truncating every asset id and UserId past
        // 2^31. Tokens/Int64.h:36-41 is the reader for this same element.
        try {
            return json {{"Int64", std::stoll(node.text().as_string())}};
        } catch (...) {
            return std::nullopt;
        }
    }
    if (token == "float")
        return json {{"Float", node.text().as_double()}};
    if (token == "double") {
        // Same reason as int64: untagged it comes back a float, losing the mantissa the file
        // stored (Tokens/Double.h:36-41).
        return json {{"Double", node.text().as_double()}};
    }
    if (token == "token")
        return json {{"Enum", node.text().as_int()}};
    if (token == "Ref") {
        const std::string referent = node.text().as_string();
        return json {{"Ref", referent.empty() || referent == "null"
            ? std::string() : referentNamespace + referent}};
    }
    if (token == "Content" || token == "ContentId") {
        // One element name, two property types: <uri> and <Ref> are the Content datatype, while
        // <url>, <binary>, <hash> and <null> are a ContentId, which serializes as a String.
        const pugi::xml_node child = node.first_child();
        const std::string_view kind = child ? std::string_view(child.name()) : std::string_view();
        if (kind == "uri")
            return json {{"Content", child.text().as_string()}};
        if (kind == "Ref")
            return std::nullopt;
        return json {{"ContentId", child ? child.text().as_string() : node.text().as_string()}};
    }
    if (token == "CoordinateFrame")
        return CFrameValue(node);
    if (token == "OptionalCoordinateFrame") {
        pugi::xml_node cframe = node.child("CFrame");
        return cframe ? std::optional<json>(CFrameValue(cframe)) : std::nullopt;
    }
    if (token == "Vector2")
        return VectorValue(node, "Vector2", {"X", "Y"});
    if (token == "Vector3")
        return VectorValue(node, "Vector3", {"X", "Y", "Z"});
    if (token == "Vector3int16")
        return VectorValue(node, "Vector3int16", {"X", "Y", "Z"});
    if (token == "Color3")
        return VectorValue(node, "Color3", {"R", "G", "B"});
    if (token == "Color3uint8") {
        uint32_t packed = 0;
        try {
            packed = static_cast<uint32_t>(std::stoull(node.text().as_string()));
        } catch (...) {
            return std::nullopt;
        }
        return json {{"Color3uint8", {
            (packed >> 16) & 0xff,
            (packed >> 8) & 0xff,
            packed & 0xff,
        }}};
    }
    if (token == "BrickColor")
        return json {{"BrickColor", node.text().as_int()}};
    if (token == "UDim")
        return VectorValue(node, "UDim", {"S", "O"});
    if (token == "UDim2") {
        return json {{"UDim2", {
            {node.child("XS").text().as_double(), node.child("XO").text().as_int()},
            {node.child("YS").text().as_double(), node.child("YO").text().as_int()},
        }}};
    }
    if (token == "Rect2D") {
        return json {{"Rect", {
            {node.child("min").child("X").text().as_double(),
             node.child("min").child("Y").text().as_double()},
            {node.child("max").child("X").text().as_double(),
             node.child("max").child("Y").text().as_double()},
        }}};
    }
    if (token == "NumberRange") {
        // Roblox writes a NumberRange as "0 5 " inner text; it has never written <Min>/<Max>
        // children, so reading those made every mounted NumberRange (0, 0).
        // Tokens/NumberRange.h:36-47 is the reader for this same element.
        const std::vector<std::string_view> parts =
            Roblox::Tokens::SplitOnSpaces(node.text().as_string());
        if (parts.size() != 2)
            return std::nullopt;
        float min = 0;
        float max = 0;
        if (!Roblox::Tokens::ParseFloat(parts[0], min) ||
            !Roblox::Tokens::ParseFloat(parts[1], max)) {
            return std::nullopt;
        }
        return json {{"NumberRange", {min, max}}};
    }
    if (token == "Axes" || token == "Faces") {
        // A single flag byte, nested one element deep in some files and bare in others --
        // Tokens/Axes.h:36-45 accepts either.
        const pugi::xml_node inner = node.first_child().type() == pugi::node_element
            ? node.first_child() : node;
        uint32_t flags = 0;
        if (!Roblox::Tokens::ParseInteger(inner.text().as_string(), flags))
            return std::nullopt;
        return json {{std::string(token), flags}};
    }
    if (token == "NumberSequence" || token == "ColorSequence") {
        // Both are space-separated tuples in the inner text, not child elements
        // (Tokens/NumberSequence.h:36-49, Tokens/ColorSequence.h:36-52).
        const std::size_t stride = token == "NumberSequence" ? 3 : 5;
        const std::vector<std::string_view> parts =
            Roblox::Tokens::SplitOnSpaces(node.text().as_string());
        if (parts.empty() || parts.size() % stride != 0)
            return std::nullopt;
        json keypoints = json::array();
        for (std::size_t index = 0; index < parts.size(); index += stride) {
            json keypoint = json::array();
            for (std::size_t field = 0; field < stride; field++) {
                float component = 0;
                if (!Roblox::Tokens::ParseFloat(parts[index + field], component))
                    return std::nullopt;
                keypoint.push_back(component);
            }
            keypoints.push_back(std::move(keypoint));
        }
        return json {{std::string(token), std::move(keypoints)}};
    }
    if (token == "BinaryString") {
        // Kept as the base64 the file spells it with: the decoded payload is arbitrary bytes and
        // a JSON string has to be valid UTF-8. PluginTreeMaterializer decodes on the way in, the
        // way Tokens/BinaryString.h:38-46 does.
        return json {{"BinaryString", node.text().as_string()}};
    }
    if (token == "Font") {
        const pugi::xml_node familyNode = node.child("Family");
        const pugi::xml_node familyUrl = familyNode.child("url");
        // CachedFaceId sits in the same <url> wrapper as Family and Font.cs:50-76 writes it
        // unconditionally, so Tokens/Font.h:41-49 always reads one back. Dropping it here left
        // every mounted face without the id the engine resolves it through.
        const pugi::xml_node cachedNode = node.child("CachedFaceId");
        const pugi::xml_node cachedUrl = cachedNode.child("url");
        return json {{"Font", {
            {"family", familyUrl ? familyUrl.text().as_string()
                                 : familyNode.text().as_string()},
            {"weight", node.child("Weight").text().as_string()},
            {"style", node.child("Style").text().as_string()},
            {"cachedFaceId", cachedUrl ? cachedUrl.text().as_string()
                                       : cachedNode.text().as_string()},
        }}};
    }
    if (token == "PhysicalProperties") {
        if (!node.child("CustomPhysics").text().as_bool())
            return json {{"PhysicalProperties", "Default"}};
        return json {{"PhysicalProperties", {
            {"density", node.child("Density").text().as_double()},
            {"friction", node.child("Friction").text().as_double()},
            {"elasticity", node.child("Elasticity").text().as_double()},
            {"frictionWeight", node.child("FrictionWeight").text().as_double()},
            {"elasticityWeight", node.child("ElasticityWeight").text().as_double()},
        }}};
    }
    if (token == "Ray") {
        pugi::xml_node origin = node.child("origin");
        pugi::xml_node direction = node.child("direction");
        return json {{"Ray", {
            {"origin", {origin.child("X").text().as_double(),
                        origin.child("Y").text().as_double(),
                        origin.child("Z").text().as_double()}},
            {"direction", {direction.child("X").text().as_double(),
                           direction.child("Y").text().as_double(),
                           direction.child("Z").text().as_double()}},
        }}};
    }
    if (unsupportedToken != nullptr)
        *unsupportedToken = token;
    return std::nullopt;
}

