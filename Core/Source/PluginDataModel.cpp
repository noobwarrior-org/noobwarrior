bool IsSerializedOnlyProperty(std::string_view propertyName) {
    // These fields are persisted by Roblox's serializer but are either engine-owned,
    // migration-only, or protected from ordinary Script threads. Replaying them from
    // the bootstrap produces capability errors and can overwrite the public property
    // that replaced an older serialized representation.
    static constexpr std::array<std::string_view, 21> kPropertyNames = {
        "AttributesSerialize",
        "Capabilities",
        "CollisionType",
        "DefinesCapabilities",
        "HistoryId",
        "InternalBodyScale",
        "InternalHeadScale",
        "LevelOfDetail",
        "LocalizationMatchIdentifier",
        "LocalizationMatchedSourceText",
        "ModelMeshCFrame",
        "ModelMeshData",
        "ModelMeshSize",
        "NeedsPivotMigration",
        "Sandboxed",
        "ScaleFactor",
        "SourceAssetId",
        "Tags",
        "UniqueId",
        "WorldPivotData",
        "formFactorRaw",
    };
    return std::find(kPropertyNames.begin(), kPropertyNames.end(), propertyName) !=
        kPropertyNames.end();
}

bool IsPerCornerRadius(std::string_view propertyName) {
    return propertyName == "BottomLeftRadius" ||
        propertyName == "BottomRightRadius" ||
        propertyName == "TopLeftRadius" ||
        propertyName == "TopRightRadius";
}

