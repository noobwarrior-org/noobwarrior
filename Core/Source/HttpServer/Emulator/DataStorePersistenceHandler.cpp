DataStorePersistenceHandler::DataStorePersistenceHandler(HttpServer *srv, EmuDbManager *dbm)
    : mHttpServer(srv), mEmuDbManager(dbm) {}

EmuDb *DataStorePersistenceHandler::SelectDb(int64_t universeId) {
    EmuDb *db = mEmuDbManager->GetFirstDbWhereItemExists(ItemType::Universe, universeId);
    if (db == nullptr)
        db = mEmuDbManager->GetMasterDatabase();
    return db;
}

int64_t DataStorePersistenceHandler::ResolveUniverseFromHeaders(evhttp_request *req) {
    if (auto u = ParseInt(RequestHeader(req, "Roblox-Universe-Id")))
        return *u;
    if (auto p = ParseInt(RequestHeader(req, "Roblox-Place-Id")))
        if (auto u = mEmuDbManager->GetUniverseIdForPlace(*p))
            return *u;
    return 0; // shared local universe
}

void DataStorePersistenceHandler::OnRequest(evhttp_request *req, void *userdata) {
    const char *uri = evhttp_request_get_uri(req);
    std::string path = uri ? uri : "";
    if (auto q = path.find('?'); q != std::string::npos)
        path.resize(q);
    std::string lpath = path;
    std::transform(lpath.begin(), lpath.end(), lpath.begin(),
                   [](unsigned char c) { return static_cast<char>(std::tolower(c)); });

    // ---- Legacy /persistence/* family ----
    if (lpath.find("/persistence/") != std::string::npos && lpath.find("/v2/persistence/") == std::string::npos) {
        if (lpath.find("getsortedvalues") != std::string::npos || lpath.find("sorted/list") != std::string::npos)
            HandleLegacySorted(req);
        else if (lpath.find("/increment") != std::string::npos)
            HandleLegacyIncrement(req);
        else if (lpath.find("/remove") != std::string::npos)
            HandleLegacyRemove(req);
        else if (lpath.find("/set") != std::string::npos)
            HandleLegacySet(req);
        else
            HandleLegacyGet(req); // getV2 + bare reads
        return;
    }

    // ---- Modern /v2/persistence/:universeId/... family ----
    int64_t universeId = 0;
    if (auto u = ParseInt(mHttpServer->GetRouteParam("universeId")))
        universeId = *u;

    auto endsWith = [&](const char *s) {
        size_t n = std::strlen(s);
        return lpath.size() >= n && lpath.compare(lpath.size() - n, n, s) == 0;
    };
    evhttp_cmd_type method = evhttp_request_get_command(req);

    if (endsWith("/object/versions/version")) {
        HandleV2Object(req, universeId, 0); // get/remove a specific version (read via the version query)
    } else if (endsWith("/object/versions")) {
        HandleV2ListVersions(req, universeId);
    } else if (endsWith("/object/increment")) {
        HandleV2Increment(req, universeId);
    } else if (endsWith("/objects/object")) {
        if (method == EVHTTP_REQ_POST && HasQueryParam(uri, "incrementBy"))
            HandleV2Increment(req, universeId);
        else if (method == EVHTTP_REQ_GET && HasQueryParam(uri, "sortOrder"))
            HandleV2ListVersions(req, universeId);
        else
            HandleV2Object(req, universeId, 0);
    } else if (endsWith("/objects")) {
        HandleV2ListObjects(req, universeId);
    } else if (endsWith("/datastores")) {
        if (HasQueryParam(uri, "datastore"))
            HandleV2ListObjects(req, universeId); // list keys within a named datastore
        else
            HandleV2ListDataStores(req, universeId);
    } else {
        HandleV2Object(req, universeId, 0);
    }
}

// GET = GetAsync (latest or a specific version), POST = SetAsync, DELETE = RemoveAsync.
void DataStorePersistenceHandler::HandleV2Object(evhttp_request *req, int64_t universeId, int dataStoreType) {
    const char *uri = evhttp_request_get_uri(req);
    EmuDb *db = SelectDb(universeId);
    if (db == nullptr) {
        SendError(req, 500, "No database available");
        return;
    }

    std::string datastore = QueryParam(uri, "datastore");
    std::string objectKey = QueryParam(uri, "objectKey");
    if (datastore.empty() || objectKey.empty()) {
        SendError(req, 400, "datastore and objectKey are required");
        return;
    }
    std::string scope, key;
    SplitObjectKey(objectKey, scope, key);

    evhttp_cmd_type method = evhttp_request_get_command(req);

    if (method == EVHTTP_REQ_GET) {
        std::string wantVersion = QueryParam(uri, "version");
        if (wantVersion.empty()) wantVersion = QueryParam(uri, "versionId");

        std::optional<EntryInfo> entry = FetchEntry(db, universeId, datastore, scope, key, dataStoreType);
        if (!entry) {
            SendKeyNotFound(req); // GetAsync -> nil
            return;
        }
        std::optional<VersionInfo> ver = FetchVersion(db, entry->Id, wantVersion);
        if (!ver || (ver->Deleted && wantVersion.empty()) || ver->ValueNull) {
            SendKeyNotFound(req);
            return;
        }
        std::string md5 = ver->Md5.empty() ? Md5Base64(ver->Value) : ver->Md5;
        AddObjectHeaders(req, ver->VersionId, entry->CreatedTime, ver->CreatedTime, ver->UserIds, ver->Attributes, md5);
        // GetAsync wants the raw value as the body (octet-stream); metadata rides in the headers above.
        // Sending application/json makes the engine parse the body as an envelope and 504.
        SendRaw(req, 200, "application/octet-stream", ver->Value);
        return;
    }

    if (method == EVHTTP_REQ_POST) {
        std::string value = ReadBody(req);
        std::string userIds = RequestHeader(req, "Roblox-Object-Userids");
        if (userIds.empty()) userIds = "[]";
        std::string attributes = RequestHeader(req, "Roblox-Object-Attributes");
        if (attributes.empty()) attributes = "{}";

        WriteResult w = WriteVersion(db, universeId, datastore, scope, key, dataStoreType, value, userIds,
                                     attributes, false, NowMs());
        if (!w.Ok) {
            SendError(req, 500, "An internal server error occurred");
            return;
        }
        AddObjectHeaders(req, w.VersionId, w.ObjectCreatedTime, w.VersionCreatedTime, userIds, attributes, w.Md5);
        // SetAsync expects the metadata envelope in the body (NOT the value echoed) — the engine reads
        // the new version from here and rejects anything else with "504: response not formatted correctly".
        json meta;
        meta["version"] = w.VersionId;
        meta["deleted"] = false;
        meta["contentLength"] = static_cast<int64_t>(value.size());
        meta["createdTime"] = MsToIso8601(w.VersionCreatedTime);
        meta["objectCreatedTime"] = MsToIso8601(w.ObjectCreatedTime);
        SendJson(req, 200, meta);
        return;
    }

    if (method == EVHTTP_REQ_DELETE) {
        std::optional<EntryInfo> entry = FetchEntry(db, universeId, datastore, scope, key, dataStoreType);
        std::string oldValue;
        bool hadValue = false;
        if (entry) {
            if (std::optional<VersionInfo> ver = FetchVersion(db, entry->Id, "")) {
                if (!ver->Deleted && !ver->ValueNull) {
                    oldValue = ver->Value;
                    hadValue = true;
                }
            }
        }
        // RemoveAsync writes a tombstone version so history (and GetVersionAsync) still works.
        WriteResult w = WriteVersion(db, universeId, datastore, scope, key, dataStoreType, std::nullopt, "[]",
                                     "{}", true, NowMs());
        if (hadValue) {
            AddObjectHeaders(req, w.VersionId, w.ObjectCreatedTime, w.VersionCreatedTime, "[]", "{}", Md5Base64(oldValue));
            SendRaw(req, 200, "application/octet-stream", oldValue);
        } else {
            SendKeyNotFound(req);
        }
        return;
    }

    SendError(req, 400, "Unsupported method");
}

void DataStorePersistenceHandler::HandleV2Increment(evhttp_request *req, int64_t universeId) {
    const char *uri = evhttp_request_get_uri(req);
    EmuDb *db = SelectDb(universeId);
    if (db == nullptr) {
        SendError(req, 500, "No database available");
        return;
    }
    std::string datastore = QueryParam(uri, "datastore");
    std::string objectKey = QueryParam(uri, "objectKey");
    if (datastore.empty() || objectKey.empty()) {
        SendError(req, 400, "datastore and objectKey are required");
        return;
    }
    std::string scope, key;
    SplitObjectKey(objectKey, scope, key);

    int64_t delta = 1;
    if (auto d = ParseInt(QueryParam(uri, "incrementBy")))
        delta = *d;

    int64_t current = 0;
    if (std::optional<EntryInfo> entry = FetchEntry(db, universeId, datastore, scope, key, 0))
        if (std::optional<VersionInfo> ver = FetchVersion(db, entry->Id, ""))
            if (!ver->Deleted)
                if (auto cur = ParseInt(ver->Value))
                    current = *cur;

    int64_t next = current + delta;
    std::string value = std::to_string(next);
    std::string userIds = RequestHeader(req, "Roblox-Object-Userids");
    if (userIds.empty()) userIds = "[]";
    std::string attributes = RequestHeader(req, "Roblox-Object-Attributes");
    if (attributes.empty()) attributes = "{}";

    WriteResult w = WriteVersion(db, universeId, datastore, scope, key, 0, value, userIds, attributes, false, NowMs());
    if (!w.Ok) {
        SendError(req, 500, "An internal server error occurred");
        return;
    }
    AddObjectHeaders(req, w.VersionId, w.ObjectCreatedTime, w.VersionCreatedTime, userIds, attributes, w.Md5);
    // IncrementAsync reads the new numeric value from the raw body (octet-stream), like GetAsync.
    SendRaw(req, 200, "application/octet-stream", value);
}

void DataStorePersistenceHandler::HandleV2ListVersions(evhttp_request *req, int64_t universeId) {
    const char *uri = evhttp_request_get_uri(req);
    EmuDb *db = SelectDb(universeId);
    if (db == nullptr) {
        SendError(req, 500, "No database available");
        return;
    }
    std::string datastore = QueryParam(uri, "datastore");
    std::string objectKey = QueryParam(uri, "objectKey");
    std::string scope, key;
    SplitObjectKey(objectKey, scope, key);

    std::string sortOrder = QueryParam(uri, "sortOrder");
    bool ascending = !sortOrder.empty() && (sortOrder[0] == 'A' || sortOrder[0] == 'a');

    json versions = json::array();
    std::optional<EntryInfo> entry = FetchEntry(db, universeId, datastore, scope, key, 0);
    if (entry) {
        SqlRows rows = db->QueryTyped(
            std::string("SELECT VersionId, Deleted, CreatedTime, ContentLength FROM DataStoreVersion WHERE EntryId=? ORDER BY Id ") +
                (ascending ? "ASC" : "DESC") + " LIMIT 200;",
            SqlValue(entry->Id));
        for (const SqlRow &r : rows) {
            json v;
            v["version"] = RowStr(r, "VersionId");
            v["deleted"] = RowI64(r, "Deleted") != 0;
            v["contentLength"] = RowI64(r, "ContentLength");
            v["createdTime"] = MsToIso8601(RowI64(r, "CreatedTime"));
            v["objectCreatedTime"] = MsToIso8601(entry->CreatedTime);
            versions.push_back(std::move(v));
        }
    }
    json j;
    j["versions"] = std::move(versions);
    j["lastReturnedKey"] = "";
    SendJson(req, 200, j);
}

void DataStorePersistenceHandler::HandleV2ListObjects(evhttp_request *req, int64_t universeId) {
    const char *uri = evhttp_request_get_uri(req);
    EmuDb *db = SelectDb(universeId);
    if (db == nullptr) {
        SendError(req, 500, "No database available");
        return;
    }
    std::string datastore = QueryParam(uri, "datastore");
    std::string prefix = QueryParam(uri, "prefix");
    std::string scope = QueryParam(uri, "scope");
    if (scope.empty()) scope = "global";
    bool allScopes = QueryParam(uri, "allScopes") == "true" || QueryParam(uri, "AllScopes") == "true";
    int limit = 50;
    if (auto m = ParseInt(QueryParam(uri, "maxItemsToReturn")))
        limit = std::clamp(static_cast<int>(*m), 1, 500);

    json keys = json::array();
    SqlRows rows;
    if (allScopes)
        rows = db->QueryTyped(
            "SELECT EntryKey, Scope FROM DataStoreEntry WHERE UniverseId=? AND DataStoreName=? AND Deleted=0 ORDER BY EntryKey ASC;",
            SqlValue(universeId), SqlValue(datastore));
    else
        rows = db->QueryTyped(
            "SELECT EntryKey, Scope FROM DataStoreEntry WHERE UniverseId=? AND DataStoreName=? AND Scope=? AND Deleted=0 ORDER BY EntryKey ASC;",
            SqlValue(universeId), SqlValue(datastore), SqlValue(scope));
    for (const SqlRow &r : rows) {
        std::string k = RowStr(r, "EntryKey");
        if (!prefix.empty() && k.rfind(prefix, 0) != 0)
            continue;
        keys.push_back(k); // ListKeysAsync expects a flat array of key strings
        if (static_cast<int>(keys.size()) >= limit)
            break;
    }
    json j;
    j["keys"] = std::move(keys);
    j["lastReturnedKey"] = "";
    SendJson(req, 200, j);
}

