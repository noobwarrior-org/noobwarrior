static const SqlValue *FindCol(const SqlRow &row, const char *name) {
    for (const auto &c : row)
        if (c.first == name) return &c.second;
    return nullptr;
}
static int64_t RowI64(const SqlRow &row, const char *name, int64_t def = 0) {
    const SqlValue *v = FindCol(row, name);
    if (!v) return def;
    if (auto p = std::get_if<int64_t>(v)) return *p;
    if (auto p = std::get_if<int>(v)) return *p;
    if (auto p = std::get_if<double>(v)) return static_cast<int64_t>(*p);
    return def;
}
static std::string RowStr(const SqlRow &row, const char *name) {
    const SqlValue *v = FindCol(row, name);
    if (!v) return "";
    if (auto p = std::get_if<std::string>(v)) return *p;
    return "";
}
static bool RowIsNull(const SqlRow &row, const char *name) {
    const SqlValue *v = FindCol(row, name);
    return !v || std::holds_alternative<std::monostate>(*v);
}

