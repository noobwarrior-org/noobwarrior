static bool ExecWrite(EmuDb *db, const std::string &sql, std::initializer_list<SqlValue> binds) {
    Statement stmt = db->PrepareStatement(sql);
    if (stmt.Fail()) return false;
    int i = 0;
    for (const auto &b : binds) {
        i++;
        stmt.Bind(i, b);
    }
    return stmt.Step() == SQLITE_DONE;
}

struct EntryInfo {
    int64_t Id = 0;
    std::string CurrentVersionId;
    bool Deleted = false;
    int64_t CreatedTime = 0;
    int64_t UpdatedTime = 0;
};

struct VersionInfo {
    std::string VersionId;
    std::string Value;
    bool ValueNull = true;
    std::string Md5;
    std::string UserIds = "[]";
    std::string Attributes = "{}";
    bool Deleted = false;
    int64_t CreatedTime = 0;
    int64_t ContentLength = 0;
};

struct WriteResult {
    bool Ok = false;
    std::string VersionId;
    int64_t ObjectCreatedTime = 0;
    int64_t VersionCreatedTime = 0;
    std::string Md5;
};

static void EnsureDataStore(EmuDb *db, int64_t universeId, const std::string &name, int type, int64_t nowMs) {
    // INSERT OR IGNORE leans on UNIQUE(UniverseId, Name, Type) to make this idempotent.
    ExecWrite(db, "INSERT OR IGNORE INTO DataStore (UniverseId, Name, Type, CreatedTime) VALUES (?,?,?,?);",
              {SqlValue(universeId), SqlValue(name), SqlValue(type), SqlValue(nowMs)});
}

static std::optional<EntryInfo> FetchEntry(EmuDb *db, int64_t universeId, const std::string &name,
                                           const std::string &scope, const std::string &key, int type) {
    SqlRows rows = db->QueryTyped(
        "SELECT Id, CurrentVersionId, Deleted, CreatedTime, UpdatedTime FROM DataStoreEntry "
        "WHERE UniverseId=? AND DataStoreName=? AND Scope=? AND EntryKey=? AND Type=? LIMIT 1;",
        SqlValue(universeId), SqlValue(name), SqlValue(scope), SqlValue(key), SqlValue(type));
    if (rows.empty()) return std::nullopt;
    const SqlRow &r = rows[0];
    EntryInfo e;
    e.Id = RowI64(r, "Id");
    e.CurrentVersionId = RowStr(r, "CurrentVersionId");
    e.Deleted = RowI64(r, "Deleted") != 0;
    e.CreatedTime = RowI64(r, "CreatedTime");
    e.UpdatedTime = RowI64(r, "UpdatedTime");
    return e;
}

static std::optional<VersionInfo> FetchVersion(EmuDb *db, int64_t entryId, const std::string &versionId) {
    SqlRows rows;
    if (versionId.empty())
        rows = db->QueryTyped(
            "SELECT VersionId, Value, ContentMd5, UserIds, Attributes, Deleted, CreatedTime, ContentLength "
            "FROM DataStoreVersion WHERE EntryId=? ORDER BY Id DESC LIMIT 1;",
            SqlValue(entryId));
    else
        rows = db->QueryTyped(
            "SELECT VersionId, Value, ContentMd5, UserIds, Attributes, Deleted, CreatedTime, ContentLength "
            "FROM DataStoreVersion WHERE EntryId=? AND VersionId=? LIMIT 1;",
            SqlValue(entryId), SqlValue(versionId));
    if (rows.empty()) return std::nullopt;
    const SqlRow &r = rows[0];
    VersionInfo v;
    v.VersionId = RowStr(r, "VersionId");
    v.ValueNull = RowIsNull(r, "Value");
    v.Value = RowStr(r, "Value");
    v.Md5 = RowStr(r, "ContentMd5");
    v.UserIds = RowStr(r, "UserIds");
    if (v.UserIds.empty()) v.UserIds = "[]";
    v.Attributes = RowStr(r, "Attributes");
    if (v.Attributes.empty()) v.Attributes = "{}";
    v.Deleted = RowI64(r, "Deleted") != 0;
    v.CreatedTime = RowI64(r, "CreatedTime");
    v.ContentLength = RowI64(r, "ContentLength");
    return v;
}

// Roblox version-id GUID format: "08<14 hex>.<10-digit seq>.08<14 hex>.01". The engine PARSES this for
// DataStoreKeyInfo.Version and rejects a plain hex string with "Unexpected Version number format" (which
// surfaces as the 504 on GetAsync). The hex parts encode the FILETIME so ids stay chronological; the
// 10-digit middle is a per-key sequence for uniqueness.
static std::string MakeVersionId(int64_t ms, int64_t seq) {
    uint64_t ft = static_cast<uint64_t>(ms) * 10000ULL + 116444736000000000ULL;
    uint64_t lo = ft & 0x00FFFFFFFFFFFFFFULL; // low 56 bits -> 14 hex chars
    char b[80];
    std::snprintf(b, sizeof(b), "08%014llX.%010lld.08%014llX.01",
                  static_cast<unsigned long long>(lo), static_cast<long long>(seq % 10000000000LL),
                  static_cast<unsigned long long>(lo));
    return b;
}

static int64_t CountVersions(EmuDb *db, int64_t entryId) {
    SqlRows rows = db->QueryTyped("SELECT COUNT(*) AS C FROM DataStoreVersion WHERE EntryId=?;", SqlValue(entryId));
    return rows.empty() ? 0 : RowI64(rows[0], "C");
}

// Writes a new value (or, with deleted=true, a tombstone) as a fresh immutable version and repoints the
// entry at it. Creates the datastore and entry rows on first use. Returns the new version's metadata.
static WriteResult WriteVersion(EmuDb *db, int64_t universeId, const std::string &name, const std::string &scope,
                                const std::string &key, int type, const std::optional<std::string> &value,
                                const std::string &userIds, const std::string &attributes, bool deleted,
                                int64_t nowMs) {
    WriteResult res;
    EnsureDataStore(db, universeId, name, type, nowMs);

    std::optional<EntryInfo> existing = FetchEntry(db, universeId, name, scope, key, type);
    int64_t entryId;
    int64_t objectCreated;
    if (existing) {
        entryId = existing->Id;
        objectCreated = existing->CreatedTime ? existing->CreatedTime : nowMs;
    } else {
        if (!ExecWrite(db,
                "INSERT INTO DataStoreEntry (UniverseId, DataStoreName, Scope, EntryKey, Type, CreatedTime, UpdatedTime) "
                "VALUES (?,?,?,?,?,?,?);",
                {SqlValue(universeId), SqlValue(name), SqlValue(scope), SqlValue(key), SqlValue(type),
                 SqlValue(nowMs), SqlValue(nowMs)}))
            return res;
        entryId = sqlite3_last_insert_rowid(db->Get());
        objectCreated = nowMs;
    }

    int64_t seq = CountVersions(db, entryId);
    std::string versionId = MakeVersionId(nowMs, seq);
    std::string md5 = value ? Md5Base64(*value) : "";
    int64_t contentLength = value ? static_cast<int64_t>(value->size()) : 0;

    if (!ExecWrite(db,
            "INSERT INTO DataStoreVersion (EntryId, VersionId, Value, ContentLength, ContentMd5, UserIds, Attributes, Deleted, CreatedTime) "
            "VALUES (?,?,?,?,?,?,?,?,?);",
            {SqlValue(entryId), SqlValue(versionId), value ? SqlValue(*value) : SqlValue(),
             SqlValue(contentLength), SqlValue(md5), SqlValue(userIds), SqlValue(attributes),
             SqlValue(deleted ? 1 : 0), SqlValue(nowMs)}))
        return res;

    std::optional<int64_t> sortVal = (value && !deleted) ? ParseInt(*value) : std::nullopt;
    if (sortVal)
        ExecWrite(db, "UPDATE DataStoreEntry SET CurrentVersionId=?, UpdatedTime=?, Deleted=?, SortValue=? WHERE Id=?;",
                  {SqlValue(versionId), SqlValue(nowMs), SqlValue(deleted ? 1 : 0), SqlValue(*sortVal), SqlValue(entryId)});
    else
        ExecWrite(db, "UPDATE DataStoreEntry SET CurrentVersionId=?, UpdatedTime=?, Deleted=?, SortValue=NULL WHERE Id=?;",
                  {SqlValue(versionId), SqlValue(nowMs), SqlValue(deleted ? 1 : 0), SqlValue(entryId)});

    db->MarkDirty();
    res.Ok = true;
    res.VersionId = versionId;
    res.ObjectCreatedTime = objectCreated;
    res.VersionCreatedTime = nowMs;
    res.Md5 = md5;
    return res;
}

// Stamps the v2 metadata headers onto a response.
static void AddObjectHeaders(evhttp_request *req, const std::string &versionId, int64_t objectCreatedMs,
                             int64_t versionCreatedMs, const std::string &userIds, const std::string &attributes,
                             const std::string &md5) {
    evkeyvalq *out = evhttp_request_get_output_headers(req);
    if (!versionId.empty()) {
        evhttp_add_header(out, "Roblox-Object-Version-Id", versionId.c_str());
        // The engine also reads the version as the ETag; SYNTAX sets both and omitting it is a candidate
        // cause of the GetAsync 504.
        std::string etag = "\"" + versionId + "\"";
        evhttp_add_header(out, "ETag", etag.c_str());
    }
    evhttp_add_header(out, "Roblox-Object-Created-Time", MsToIso8601(objectCreatedMs).c_str());
    evhttp_add_header(out, "Roblox-Object-Version-Created-Time", MsToIso8601(versionCreatedMs).c_str());
    if (!userIds.empty())
        evhttp_add_header(out, "Roblox-Object-Userids", userIds.c_str());
    if (!attributes.empty())
        evhttp_add_header(out, "Roblox-Object-Attributes", attributes.c_str());
    if (!md5.empty())
        evhttp_add_header(out, "Content-MD5", md5.c_str());
}

