// Legacy /persistence/* (key=datastore, target=entry key, scope=scope)
// ============================================================================================

// Builds one legacy result object: {"Key":{"Scope":..,"Target":..,"Key":..},"Value":"<json text>"}.
static json LegacyEntryJson(const std::string &scope, const std::string &target, const std::string &datastore,
                            const std::string &value) {
    json k;
    k["Scope"] = scope;
    k["Target"] = target;
    k["Key"] = datastore;
    json e;
    e["Key"] = std::move(k);
    e["Value"] = value; // nlohmann emits the stored JSON text as a JSON string, matching Roblox
    return e;
}

void DataStorePersistenceHandler::HandleLegacyGet(evhttp_request *req) {
    const char *uri = evhttp_request_get_uri(req);
    int64_t universeId = ResolveUniverseFromHeaders(req);
    EmuDb *db = SelectDb(universeId);
    if (db == nullptr) {
        SendError(req, 500, "No database available");
        return;
    }

    json data = json::array();

    // Batch form: qkeys[i].scope / qkeys[i].target / qkeys[i].key in the POST body.
    std::string body = ReadBody(req);
    bool didBatch = false;
    if (!body.empty() && body.find("qkeys") != std::string::npos) {
        evkeyvalq form;
        if (evhttp_parse_query_str(body.c_str(), &form) == 0) {
            for (int i = 0;; i++) {
                std::string base = "qkeys[" + std::to_string(i) + "].";
                const char *ds = evhttp_find_header(&form, (base + "key").c_str());
                if (!ds) break;
                const char *tg = evhttp_find_header(&form, (base + "target").c_str());
                const char *sc = evhttp_find_header(&form, (base + "scope").c_str());
                std::string datastore = ds;
                std::string target = tg ? tg : "";
                std::string scope = (sc && *sc) ? sc : "global";
                if (auto entry = FetchEntry(db, universeId, datastore, scope, target, 0))
                    if (auto ver = FetchVersion(db, entry->Id, ""))
                        if (!ver->Deleted && !ver->ValueNull)
                            data.push_back(LegacyEntryJson(scope, target, datastore, ver->Value));
                didBatch = true;
            }
            evhttp_clear_headers(&form);
        }
    }

    // Single form: ?key=<datastore>&scope=<scope>&target=<key>
    if (!didBatch) {
        std::string datastore = QueryParam(uri, "key");
        std::string target = QueryParam(uri, "target");
        std::string scope = QueryParam(uri, "scope");
        if (scope.empty()) scope = "global";
        if (!datastore.empty()) {
            if (auto entry = FetchEntry(db, universeId, datastore, scope, target, 0))
                if (auto ver = FetchVersion(db, entry->Id, ""))
                    if (!ver->Deleted && !ver->ValueNull)
                        data.push_back(LegacyEntryJson(scope, target, datastore, ver->Value));
        }
    }

    json j;
    j["data"] = std::move(data);
    SendJson(req, 200, j);
}

