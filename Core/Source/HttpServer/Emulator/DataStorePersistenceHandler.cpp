void DataStorePersistenceHandler::HandleLegacySorted(evhttp_request *req) {
    const char *uri = evhttp_request_get_uri(req);
    int64_t universeId = ResolveUniverseFromHeaders(req);
    EmuDb *db = SelectDb(universeId);
    if (db == nullptr) {
        SendError(req, 500, "No database available");
        return;
    }
    std::string datastore = QueryParam(uri, "key");
    std::string scope = QueryParam(uri, "scope");
    if (scope.empty()) scope = "global";
    std::string direction = QueryParam(uri, "direction");
    bool ascending = direction.empty() || direction[0] == 'a' || direction[0] == 'A';
    int pageSize = 50;
    if (auto p = ParseInt(QueryParam(uri, "pageSize")))
        pageSize = std::clamp(static_cast<int>(*p), 1, 100);
    std::optional<int64_t> minValue = ParseInt(QueryParam(uri, "minValue"));
    std::optional<int64_t> maxValue = ParseInt(QueryParam(uri, "maxValue"));

    // OrderedDataStore ranks keys by their numeric SortValue. Entries are written through the same
    // tables; ordered ones simply have a non-null SortValue.
    std::string sql =
        "SELECT EntryKey, SortValue FROM DataStoreEntry "
        "WHERE UniverseId=? AND DataStoreName=? AND Scope=? AND Deleted=0 AND SortValue IS NOT NULL";
    if (minValue) sql += " AND SortValue >= " + std::to_string(*minValue);
    if (maxValue) sql += " AND SortValue <= " + std::to_string(*maxValue);
    sql += ascending ? " ORDER BY SortValue ASC" : " ORDER BY SortValue DESC";
    sql += " LIMIT " + std::to_string(pageSize) + ";";

    SqlRows rows = db->QueryTyped(sql, SqlValue(universeId), SqlValue(datastore), SqlValue(scope));
    json entries = json::array();
    for (const SqlRow &r : rows) {
        json e;
        e["Target"] = RowStr(r, "EntryKey");
        e["Value"] = RowI64(r, "SortValue");
        entries.push_back(std::move(e));
    }
    json inner;
    inner["Entries"] = std::move(entries);
    inner["ExclusiveStartKey"] = nullptr;
    json j;
    j["data"] = std::move(inner);
    SendJson(req, 200, j);
}
