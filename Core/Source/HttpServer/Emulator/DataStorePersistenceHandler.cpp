// One decoded query parameter, or "" when absent. evhttp_parse_query url-decodes values, so an
// objectKey of "global%2Ftest_key" comes back as "global/test_key".
static std::string QueryParam(const char *uri, const char *key) {
    std::string out;
    if (uri == nullptr) return out;
    evkeyvalq query;
    if (evhttp_parse_query(uri, &query) == 0) {
        if (const char *val = evhttp_find_header(&query, key))
            out = val;
        evhttp_clear_headers(&query);
    }
    return out;
}

static bool HasQueryParam(const char *uri, const char *key) {
    if (uri == nullptr) return false;
    bool found = false;
    evkeyvalq query;
    if (evhttp_parse_query(uri, &query) == 0) {
        found = evhttp_find_header(&query, key) != nullptr;
        evhttp_clear_headers(&query);
    }
    return found;
}

static std::string RequestHeader(evhttp_request *req, const char *name) {
    const char *v = evhttp_find_header(evhttp_request_get_input_headers(req), name);
    return v ? std::string(v) : std::string();
}

// Inflates gzip/zlib in place (Studio gzip-compresses POST bodies). Auto-detects the wrapper.
static bool Inflate(const std::string &in, std::string &out) {
    if (in.empty()) return false;
    z_stream zs{};
    if (inflateInit2(&zs, 15 + 32) != Z_OK)
        return false;
    zs.next_in = reinterpret_cast<Bytef *>(const_cast<char *>(in.data()));
    zs.avail_in = static_cast<uInt>(in.size());
    char buf[8192];
    int ret;
    do {
        zs.next_out = reinterpret_cast<Bytef *>(buf);
        zs.avail_out = sizeof(buf);
        ret = inflate(&zs, Z_NO_FLUSH);
        if (ret != Z_OK && ret != Z_STREAM_END && ret != Z_BUF_ERROR) {
            inflateEnd(&zs);
            return false;
        }
        out.append(buf, sizeof(buf) - zs.avail_out);
    } while (ret == Z_OK);
    inflateEnd(&zs);
    return ret == Z_STREAM_END;
}

// The full request body, transparently inflated when gzip-encoded.
static std::string ReadBody(evhttp_request *req) {
    std::string body;
    if (evbuffer *in = evhttp_request_get_input_buffer(req)) {
        size_t len = evbuffer_get_length(in);
        body.resize(len);
        if (len > 0)
            evbuffer_copyout(in, body.data(), len);
    }
    if (body.empty()) return body;
    const char *enc = evhttp_find_header(evhttp_request_get_input_headers(req), "Content-Encoding");
    bool looksGzip = body.size() >= 2 && static_cast<unsigned char>(body[0]) == 0x1f &&
                     static_cast<unsigned char>(body[1]) == 0x8b;
    if ((enc && std::strstr(enc, "gzip")) || looksGzip) {
        std::string inflated;
        if (Inflate(body, inflated))
            body = std::move(inflated);
    }
    return body;
}

static int64_t NowMs() {
    return std::chrono::duration_cast<std::chrono::milliseconds>(
               std::chrono::system_clock::now().time_since_epoch())
        .count();
}

// ISO-8601 UTC with a numeric offset and no fractional seconds ("2026-06-23T20:45:38+00:00"). This is
// exactly what PHP date('c') emits, which the engine's DataStoreKeyInfo time parser accepts; the
// fractional ".sssZ" form is rejected by GetAsync (it builds KeyInfo and parses these), surfacing as
// the 504 even though SetAsync — which only reads "version" — tolerated it.
static std::string MsToIso8601(int64_t ms) {
    std::time_t secs = static_cast<std::time_t>(ms / 1000);
    std::tm tmv{};
#if defined(_WIN32)
    gmtime_s(&tmv, &secs);
#else
    gmtime_r(&secs, &tmv);
#endif
    char buf[40];
    std::snprintf(buf, sizeof(buf), "%04d-%02d-%02dT%02d:%02d:%02d+00:00",
                  tmv.tm_year + 1900, tmv.tm_mon + 1, tmv.tm_mday, tmv.tm_hour, tmv.tm_min, tmv.tm_sec);
    return buf;
}

// base64(md5(data)) — the Content-MD5 value the engine validates.
static std::string Md5Base64(const std::string &data) {
    unsigned char digest[EVP_MAX_MD_SIZE];
    unsigned int len = 0;
    if (EVP_Digest(data.data(), data.size(), digest, &len, EVP_md5(), nullptr) != 1)
        return "";
    return base64_encode(digest, len);
}

static const char *ReasonFor(int code) {
    switch (code) {
    case 200: return "OK";
    case 204: return "No Content";
    case 400: return "Bad Request";
    case 403: return "Forbidden";
    case 404: return "Not Found";
    case 409: return "Conflict";
    case 429: return "Too Many Requests";
    case 500: return "Internal Server Error";
    default:  return "OK";
    }
}

static void SendRaw(evhttp_request *req, int code, const std::string &contentType, const std::string &body) {
    if (!contentType.empty())
        evhttp_add_header(evhttp_request_get_output_headers(req), "Content-Type", contentType.c_str());
    evbuffer *buf = evbuffer_new();
    if (!body.empty())
        evbuffer_add(buf, body.data(), body.size());
    evhttp_send_reply(req, code, ReasonFor(code), buf);
    evbuffer_free(buf);
}

static void SendJson(evhttp_request *req, int code, const json &j) {
    SendRaw(req, code, "application/json", j.dump());
}

// The DataStore error envelope. The engine surfaces these as e.g. "DataStoreService: <message>".
static void SendError(evhttp_request *req, int code, const std::string &message) {
    json e;
    e["code"] = code;
    e["message"] = message;
    json j;
    j["errors"] = json::array({e});
    SendRaw(req, code, "application/json", j.dump());
}

// 404 the engine treats as "key not found" -> GetAsync/RemoveAsync return nil instead of throwing.
static void SendKeyNotFound(evhttp_request *req) {
    json e;
    e["code"] = 11;
    e["message"] = "The requested key does not exist.";
    e["retryable"] = false;
    json j;
    j["errors"] = json::array({e});
    SendRaw(req, 404, "application/json", j.dump());
}

// Splits an objectKey ("scope/key") into its scope and key. Scope can't contain '/', keys can, so we
// split on the first slash. A bare value (no slash) is treated as a key in the default "global" scope.
static void SplitObjectKey(const std::string &objectKey, std::string &scope, std::string &key) {
    auto slash = objectKey.find('/');
    if (slash == std::string::npos) {
        scope = "global";
        key = objectKey;
    } else {
        scope = objectKey.substr(0, slash);
        key = objectKey.substr(slash + 1);
    }
    if (scope.empty()) scope = "global";
}

static std::optional<int64_t> ParseInt(const std::string &s) {
    if (s.empty()) return std::nullopt;
    char *end = nullptr;
    long long v = strtoll(s.c_str(), &end, 10);
    if (end == s.c_str() || *end != '\0') return std::nullopt;
    return static_cast<int64_t>(v);
}

