// Description: Implements the DataStoreService persistence wire protocol over the EmuDb v17 tables.
//
//   The modern engine (0.574+) talks to gamepersistence.roblox.com:
//     GET    /v2/persistence/{universeId}/datastores/objects/object?datastore=&objectKey=     GetAsync
//     POST   /v2/persistence/{universeId}/datastores/objects/object?datastore=&objectKey=     SetAsync
//     POST   .../objects/object?...&incrementBy=N      (or .../object/increment)              IncrementAsync
//     DELETE /v2/persistence/{universeId}/datastores/objects/object?datastore=&objectKey=     RemoveAsync
//     GET    .../objects/object?...&sortOrder=  (or .../object/versions)                      ListVersionsAsync
//     GET    /v2/persistence/{universeId}/datastores/objects?datastore=&prefix=               ListKeysAsync
//     GET    /v2/persistence/{universeId}/datastores?prefix=                                  ListDataStoresAsync
//   The value is carried in the request/response BODY; version id, created times, user ids and
//   attributes ride in Roblox-Object-* headers and the checksum in Content-MD5 (all verified against
//   the 0.574 RobloxStudioBeta.exe string table).
//
//   Older engines use the legacy form where the query param "key" is the datastore name, "target" is
//   the entry key and "scope" is the scope:
//     POST/GET /persistence/getV2     GetAsync (single via query, or batch via qkeys[] body)
//     POST     /persistence/set       SetAsync (value in body, valueLength query)
//     POST     /persistence/increment IncrementAsync
//     POST     /persistence/remove    RemoveAsync
//     GET      /persistence/getSortedValues   OrderedDataStore:GetSortedAsync
//
//   (Code generated by Claude Opus 4.8)
