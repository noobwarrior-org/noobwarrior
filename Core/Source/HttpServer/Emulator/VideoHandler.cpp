// A path segment from the URL is never allowed to reach the filesystem unchecked. Only the shapes
// VideoTranscoder actually produces are accepted: "index.m3u8" and "segN.ts".
bool IsSafeFileName(const std::string &name) {
    // Long enough for "<64 hex chars>-<index>.ts", which is how VideoTranscoder names segments.
    if (name.empty() || name.size() > 96)
        return false;
    if (name.find('/') != std::string::npos || name.find('\\') != std::string::npos)
        return false;
    if (name.find("..") != std::string::npos)
        return false;
    for (char c : name) {
        const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
                     || (c >= '0' && c <= '9') || c == '.' || c == '-' || c == '_';
        if (!ok)
            return false;
    }
    return true;
}

// The cache directory name is built from this, so it gets the same treatment.
bool IsSafeHash(const std::string &hash) {
    if (hash.empty() || hash.size() > 128)
        return false;
    for (char c : hash) {
        const bool ok = (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F') || (c >= '0' && c <= '9');
        if (!ok)
            return false;
    }
    return true;
}

const char *ContentTypeFor(const std::string &fileName) {
    // The engine ignores these -- onAssetLoadedContentBase does no Content-Type sniffing -- but a
    // browser hitting the same URL to debug a playlist very much does not.
    if (fileName.ends_with(".m3u8")) return "application/vnd.apple.mpegurl";
    if (fileName.ends_with(".ts"))   return "video/MP2T";
    return "application/octet-stream";
}

bool UriNeedsPrefix(const std::string &uri) {
    if (uri.empty())
        return false;
    if (uri.front() == '/')
        return false;                    // already an absolute path, or protocol-relative
    return uri.find("://") == std::string::npos;       // anything with a scheme is left alone
}

std::string RewritePlaylist(const std::vector<unsigned char> &data, const std::string &prefix) {
    const std::string text(reinterpret_cast<const char*>(data.data()), data.size());

    std::string out;
    out.reserve(text.size() + 64);

    size_t pos = 0;
    while (pos < text.size()) {
        size_t lineEnd = text.find('\n', pos);
        const bool lastLine = lineEnd == std::string::npos;
        if (lastLine)
            lineEnd = text.size();

        std::string line = text.substr(pos, lineEnd - pos);
        pos = lineEnd + 1;

        std::string terminator = lastLine ? std::string() : std::string("\n");
        if (!line.empty() && line.back() == '\r') {
            line.pop_back();
            terminator = lastLine ? std::string("\r") : std::string("\r\n");
        }

        // Only a bare URI line names a segment; every tag emitted by -hls_segment_type mpegts carries
        // its value inline, so there is no attribute to rewrite.
        if (!line.empty() && line[0] != '#' && UriNeedsPrefix(line))
            line = prefix + line;

        out += line;
        out += terminator;
    }
    return out;
}


