// Standard base64 (the ACR parameter is padded and uses +/), tolerating the URL-safe alphabet too.
// AuthUtil::Base64UrlDecode only accepts -_ and rejects padding, so it cannot be reused here.
static std::string DecodeBase64(std::string_view encoded) {
    auto value = [](char c) -> int {
        if (c >= 'A' && c <= 'Z') return c - 'A';
        if (c >= 'a' && c <= 'z') return c - 'a' + 26;
        if (c >= '0' && c <= '9') return c - '0' + 52;
        // evhttp_parse_query form-decodes the value, so a '+' in the base64 alphabet reaches us as a
        // space. Mapping it back matters: skipping it instead would shift every following sextet and
        // quietly decode to garbage.
        if (c == '+' || c == '-' || c == ' ') return 62;
        if (c == '/' || c == '_') return 63;
        return -1;
    };
    std::string out;
    uint32_t buf = 0;
    int bits = 0;
    for (char c : encoded) {
        if (c == '=')
            break;
        const int v = value(c);
        if (v < 0)
            continue; // whitespace or stray percent-decoding leftovers
        buf = (buf << 6) | static_cast<uint32_t>(v);
        bits += 6;
        if (bits >= 8) {
            bits -= 8;
            out += static_cast<char>((buf >> bits) & 0xFF);
        }
    }
    return out;
}

bool VideoHandler::AcrRequestsHls(const char *encoded) {
    if (encoded == nullptr || *encoded == 0)
        return false;

    const std::string json = DecodeBase64(encoded);
    if (json.empty())
        return false;

    const nlohmann::json parsed = nlohmann::json::parse(json, nullptr, false);
    if (!parsed.is_array())
        return false;

    for (const auto &entry : parsed) {
        if (entry.is_object() && entry.value("format", std::string {}) == "hls")
            return true;
    }
    return false;
}

