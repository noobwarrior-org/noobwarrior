// Every .rbxm the plan walker met produced exactly one "model" node, and
// FinalizePlan in PluginDataModel.cpp rewrote that node's kind to
// "embeddedModel" in place. PluginManager::BuildStudioServerBootstrap flattens every plugin's
// plans and models into two lists, so this count is all that is left of the association between
// a plan and the models that were built alongside it.
size_t CountEmbeddedModels(const nlohmann::json &node) {
    size_t total = 0;
    if (node.is_array()) {
        for (const nlohmann::json &child : node)
            total += CountEmbeddedModels(child);
        return total;
    }
    if (!node.is_object())
        return 0;
    // Read without json::value(), which throws when a key holds an unexpected type.
    const auto kind = node.find("kind");
    if (kind != node.end() && kind->is_string() && kind->get_ref<const std::string &>() ==
        "embeddedModel") {
        ++total;
    }
    const auto children = node.find("children");
    if (children != node.end())
        total += CountEmbeddedModels(*children);
    return total;
}

bool SpliceBinaryModel(Roblox::BinaryFormat::BinaryRobloxFile &binary,
                       const StudioServerModel &model, PluginMountResult &mounted,
                       std::string *error) {
    std::vector<Roblox::BinaryFormat::BinaryModelPathElement> parentPath;
    parentPath.reserve(model.ParentPath.size());
    for (const StudioServerModelPathElement &element : model.ParentPath)
        parentPath.push_back({element.Name, element.ClassName});
    size_t replaced = 0;
    if (!binary.AppendBinaryModel(model.Data, parentPath, model.SingleRootName, error,
                                  &replaced)) {
        return false;
    }
    mounted.Replaced += static_cast<int>(replaced);
    return true;
}
