std::string ComputeStudioServerPlaceCacheKey(
    std::string_view sourceSha256, const StudioServerBootstrap &bootstrap,
    std::string_view studioFingerprint, uint32_t schemaVersion) {
    using Context = std::unique_ptr<EVP_MD_CTX, decltype(&EVP_MD_CTX_free)>;
    Context context(EVP_MD_CTX_new(), EVP_MD_CTX_free);
    if (!context || EVP_DigestInit_ex(context.get(), EVP_sha256(), nullptr) != 1 ||
        !DigestString(context.get(), kCacheDomain) ||
        !DigestUint64(context.get(), schemaVersion) ||
        !DigestString(context.get(), sourceSha256) ||
        !DigestString(context.get(), studioFingerprint) ||
        !DigestUint64(context.get(), bootstrap.Plans.size()) ||
        !DigestUint64(context.get(), bootstrap.Scripts.size()) ||
        !DigestUint64(context.get(), bootstrap.Models.size())) {
        return {};
    }

    for (const std::string &plan : bootstrap.Plans) {
        if (!DigestString(context.get(), plan))
            return {};
    }
    for (const StudioServerScript &script : bootstrap.Scripts) {
        const unsigned char disabled = script.Disabled ? 1 : 0;
        if (!DigestString(context.get(), script.Key) ||
            !DigestString(context.get(), script.ClassName) ||
            !DigestString(context.get(), script.Source) ||
            !DigestString(context.get(), script.ParentClassName) ||
            !DigestBytes(context.get(), &disabled, sizeof(disabled))) {
            return {};
        }
    }
    for (const StudioServerModel &model : bootstrap.Models) {
        if (!DigestString(context.get(), model.SourcePath) ||
            !DigestUint64(context.get(), model.ParentPath.size())) {
            return {};
        }
        for (const StudioServerModelPathElement &element : model.ParentPath) {
            if (!DigestString(context.get(), element.Name) ||
                !DigestString(context.get(), element.ClassName)) {
                return {};
            }
        }
        if (!DigestString(context.get(), model.SingleRootName) ||
            !DigestUint64(context.get(), model.Data.size()) ||
            !DigestBytes(context.get(), model.Data.data(), model.Data.size())) {
            return {};
        }
    }
    return FinishDigest(context.get());
}

std::string ComputeStudioServerPlaceSourceHash(std::span<const unsigned char> place) {
    using Context = std::unique_ptr<EVP_MD_CTX, decltype(&EVP_MD_CTX_free)>;
    Context context(EVP_MD_CTX_new(), EVP_MD_CTX_free);
    if (!context || EVP_DigestInit_ex(context.get(), EVP_sha256(), nullptr) != 1 ||
        !DigestBytes(context.get(), place.data(), place.size())) {
        return {};
    }
    return FinishDigest(context.get());
}

std::filesystem::path StudioServerPlaceCacheEntry(
    const std::filesystem::path &cacheDirectory, std::string_view cacheKey) {
    if (!IsHexDigest(cacheKey))
        return {};
    return cacheDirectory / (std::string(cacheKey) + ".rbxl");
}

StudioServerPlaceCacheResponse PublishCachedStudioServerPlace(
    const std::filesystem::path &cacheDirectory, std::string_view cacheKey,
    const std::filesystem::path &launchPath, uint64_t *placeBytes,
    std::string *error,
    const StudioServerPlacePublishCallback &publishCallback) {
    const std::filesystem::path cachePath =
        StudioServerPlaceCacheEntry(cacheDirectory, cacheKey);
    if (cachePath.empty()) {
        SetError(error, "invalid Studio server place cache key");
        return StudioServerPlaceCacheResponse::Failed;
    }

    uint64_t expectedSize = 0;
    if (!ReadExpectedSize(cachePath, expectedSize))
        return StudioServerPlaceCacheResponse::Miss;
    std::error_code code;
    if (std::filesystem::file_size(cachePath, code) != expectedSize || code)
        return StudioServerPlaceCacheResponse::Miss;
    if (publishCallback)
        publishCallback(expectedSize);

    PublishLock lock;
    if (!lock.Locked()) {
        SetError(error, "could not lock the Studio server launch path");
        return StudioServerPlaceCacheResponse::Failed;
    }
    const CopyResponse copied = CopyAtomically(cachePath, launchPath, error);
    if (copied == CopyResponse::SourceUnavailable)
        return StudioServerPlaceCacheResponse::Miss;
    if (copied != CopyResponse::Success)
        return StudioServerPlaceCacheResponse::Failed;

    if (placeBytes != nullptr)
        *placeBytes = expectedSize;
    // Both halves of the entry are touched, so a prune that still ages files independently -- an
    // older noobWarrior sharing this cache directory, or the user's own cleanup -- cannot take
    // the size record of an entry that is being hit.
    const auto touched = std::filesystem::file_time_type::clock::now();
    std::filesystem::last_write_time(cachePath, touched, code);
    std::filesystem::last_write_time(SizePath(cachePath), touched, code);
    return StudioServerPlaceCacheResponse::Hit;
}

bool StoreStudioServerPlaceCache(
    const std::filesystem::path &cacheDirectory, std::string_view cacheKey,
    std::span<const unsigned char> place, std::string *error) {
    const std::filesystem::path cachePath =
        StudioServerPlaceCacheEntry(cacheDirectory, cacheKey);
    if (cachePath.empty()) {
        SetError(error, "invalid Studio server place cache key");
        return false;
    }
    if (place.empty()) {
        SetError(error, "refusing to cache an empty Studio server place");
        return false;
    }
    if (!WriteAtomically(cachePath, place, error))
        return false;

    // The size record lands second, so an interrupted store reads back as a miss rather than as a
    // complete entry.
    const std::string size = std::to_string(place.size()) + "\n";
    const std::span<const unsigned char> sizeBytes(
        reinterpret_cast<const unsigned char *>(size.data()), size.size());
    // A size record that never lands leaves an entry that reads back as a miss and is pruned by
    // age, which is the whole reason it is written second. Deleting the place here instead would
    // let one failed store destroy an entry a concurrent builder had just published correctly.
    if (!WriteAtomically(SizePath(cachePath), sizeBytes, error))
        return false;

    PruneCache(cacheDirectory, cachePath);
    return true;
}

bool PublishStudioServerPlace(
    const std::filesystem::path &launchPath, std::span<const unsigned char> place,
    std::string *error) {
    PublishLock lock;
    if (!lock.Locked()) {
        SetError(error, "could not lock the Studio server launch path");
        return false;
    }
    return WriteAtomically(launchPath, place, error);
}

StudioServerPlacePreparationResponse PrepareStudioServerPlace(
    std::string_view sourceSha256, const StudioServerBootstrap &bootstrap,
    std::string_view studioFingerprint, const std::filesystem::path &cacheDirectory,
    const std::filesystem::path &launchPath, const StudioServerPlaceLoader &loader,
    uint64_t *placeBytes, std::string *error,
    const StudioServerPlacePublishCallback &publishCallback) {
    if (error != nullptr)
        error->clear();
    const std::string cacheKey = ComputeStudioServerPlaceCacheKey(
        sourceSha256, bootstrap, studioFingerprint);
    if (cacheKey.empty()) {
        SetError(error, "could not compute Studio server place cache key");
        return StudioServerPlacePreparationResponse::Failed;
    }

    const StudioServerPlaceCacheResponse cached = PublishCachedStudioServerPlace(
        cacheDirectory, cacheKey, launchPath, placeBytes, error, publishCallback);
    if (cached == StudioServerPlaceCacheResponse::Hit)
        return StudioServerPlacePreparationResponse::CacheHit;
    if (cached == StudioServerPlaceCacheResponse::Failed)
        return StudioServerPlacePreparationResponse::Failed;

    // A miss simply means this process builds the entry. Concurrent builders of the same key
    // produce identical bytes, so the loser's work is redundant rather than harmful.
    if (error != nullptr)
        error->clear();
    std::vector<unsigned char> place;
    if (!loader || !loader(place, error) || place.empty()) {
        if (error != nullptr && error->empty())
            *error = "could not load Studio server place";
        return StudioServerPlacePreparationResponse::Failed;
    }
    const std::string actualSourceHash = ComputeStudioServerPlaceSourceHash(place);
    if (actualSourceHash.empty() || actualSourceHash != sourceSha256) {
        SetError(error, "Studio server place bytes do not match AssetData.DataHash");
        return StudioServerPlacePreparationResponse::Failed;
    }

    if (!bootstrap.Empty() && !InjectStudioServerBootstrap(place, bootstrap, error))
        return StudioServerPlacePreparationResponse::Failed;

    if (publishCallback)
        publishCallback(place.size());
    std::string cacheError;
    if (!StoreStudioServerPlaceCache(cacheDirectory, cacheKey, place, &cacheError)) {
        // Not fatal -- the launch goes ahead with the place this process just built. It is still
        // worth printing: a store that keeps failing makes every single launch pay for a rebuild.
        Out("StudioServerPlaceCache",
            "WARNING! Could not cache the prepared Studio server place: {}",
            cacheError.empty() ? std::string("unknown error") : cacheError);
    }

    if (error != nullptr)
        error->clear();
    if (!PublishStudioServerPlace(launchPath, place, error))
        return StudioServerPlacePreparationResponse::Failed;
    if (placeBytes != nullptr)
        *placeBytes = place.size();
    return StudioServerPlacePreparationResponse::Built;
}
