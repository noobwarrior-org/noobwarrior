constexpr std::string_view kCacheDomain = "noobWarrior/studio-server-place-cache";
// A prepared place is only worth keeping while its plugin set and Studio build stay put. Every hit
// touches its entry, so anything untouched for this long belongs to a configuration the user has
// moved on from.
constexpr auto kCacheEntryLifetime = std::chrono::hours(24 * 14);
std::atomic_uint64_t gTemporaryCounter {0};

void SetError(std::string *error, std::string message) {
    if (error != nullptr)
        *error = std::move(message);
}

bool IsHexDigest(std::string_view value) {
    return value.size() == 64 && std::ranges::all_of(value, [](unsigned char character) {
        return (character >= '0' && character <= '9') ||
               (character >= 'a' && character <= 'f');
    });
}

bool DigestBytes(EVP_MD_CTX *context, const void *data, size_t size) {
    return size == 0 || EVP_DigestUpdate(context, data, size) == 1;
}

bool DigestUint64(EVP_MD_CTX *context, uint64_t value) {
    std::array<unsigned char, sizeof(value)> encoded {};
    for (size_t index = 0; index < encoded.size(); ++index)
        encoded[index] = static_cast<unsigned char>(value >> (index * 8));
    return DigestBytes(context, encoded.data(), encoded.size());
}

bool DigestString(EVP_MD_CTX *context, std::string_view value) {
    return DigestUint64(context, value.size()) &&
           DigestBytes(context, value.data(), value.size());
}

std::string FinishDigest(EVP_MD_CTX *context) {
    std::array<unsigned char, EVP_MAX_MD_SIZE> digest {};
    unsigned int digestSize = 0;
    if (EVP_DigestFinal_ex(context, digest.data(), &digestSize) != 1 || digestSize != 32)
        return {};

    std::ostringstream encoded;
    encoded << std::hex << std::setfill('0');
    for (unsigned int index = 0; index < digestSize; ++index)
        encoded << std::setw(2) << static_cast<unsigned int>(digest[index]);
    return encoded.str();
}

uint64_t ProcessId() {
#if defined(_WIN32)
    return GetCurrentProcessId();
#else
    return static_cast<uint64_t>(getpid());
#endif
}

std::filesystem::path TemporaryPathFor(const std::filesystem::path &destination) {
    std::filesystem::path temporary = destination;
    temporary += ".tmp-" + std::to_string(ProcessId()) + "-" +
                 std::to_string(gTemporaryCounter.fetch_add(1, std::memory_order_relaxed));
    return temporary;
}

bool ReplaceAtomically(const std::filesystem::path &temporary,
                       const std::filesystem::path &destination,
                       std::string *error) {
#if defined(_WIN32)
    if (MoveFileExW(temporary.c_str(), destination.c_str(),
                    MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH)) {
        return true;
    }
    SetError(error, "could not atomically replace " + destination.string() +
                    " (Windows error " + std::to_string(GetLastError()) + ")");
    return false;
#else
    std::error_code code;
    std::filesystem::rename(temporary, destination, code);
    if (!code)
        return true;
    SetError(error, "could not atomically replace " + destination.string() +
                    ": " + code.message());
    return false;
#endif
}

bool WriteAtomically(const std::filesystem::path &destination,
                     std::span<const unsigned char> data, std::string *error) {
    std::error_code code;
    const std::filesystem::path parent = destination.parent_path();
    if (!parent.empty()) {
        std::filesystem::create_directories(parent, code);
        if (code) {
            SetError(error, "could not create " + parent.string() + ": " + code.message());
            return false;
        }
    }

    const std::filesystem::path temporary = TemporaryPathFor(destination);
    {
        std::ofstream stream(temporary, std::ios::binary | std::ios::trunc);
        if (!stream.is_open()) {
            SetError(error, "could not open " + temporary.string() + " for writing");
            return false;
        }
        stream.write(reinterpret_cast<const char *>(data.data()),
                     static_cast<std::streamsize>(data.size()));
        stream.close();
        if (!stream) {
            std::filesystem::remove(temporary, code);
            SetError(error, "could not completely write " + temporary.string());
            return false;
        }
    }

    if (ReplaceAtomically(temporary, destination, error))
        return true;
    std::filesystem::remove(temporary, code);
    return false;
}

std::filesystem::path SizePath(const std::filesystem::path &cachePath) {
    std::filesystem::path size = cachePath;
    size += ".size";
    return size;
}

// Entries are published by an atomic rename, so a short read means something outside noobWarrior
// truncated one. Recording the expected length costs a single stat on the hot path and turns that
// case into a rebuild instead of a server.rbxl that fails to load on every launch from then on.
bool ReadExpectedSize(const std::filesystem::path &cachePath, uint64_t &size) {
    std::ifstream stream(SizePath(cachePath), std::ios::binary);
    std::string line;
    if (!std::getline(stream, line))
        return false;
    const auto parsed = std::from_chars(line.data(), line.data() + line.size(), size);
    return parsed.ec == std::errc {} && parsed.ptr == line.data() + line.size() && size > 0;
}

enum class CopyResponse {
    Success,
    SourceUnavailable,
    Failed,
};

CopyResponse CopyAtomically(const std::filesystem::path &source,
                            const std::filesystem::path &destination,
                            std::string *error) {
    std::error_code code;
    const std::filesystem::path parent = destination.parent_path();
    if (!parent.empty()) {
        std::filesystem::create_directories(parent, code);
        if (code) {
            SetError(error, "could not create " + parent.string() + ": " + code.message());
            return CopyResponse::Failed;
        }
    }

    const std::filesystem::path temporary = TemporaryPathFor(destination);
    std::filesystem::copy_file(source, temporary,
                               std::filesystem::copy_options::overwrite_existing, code);
    if (code) {
        std::error_code ignored;
        std::filesystem::remove(temporary, ignored);
        if (!std::filesystem::exists(source, ignored)) {
            SetError(error, "cached Studio server place disappeared before publication");
            return CopyResponse::SourceUnavailable;
        }
        SetError(error, "could not copy the cached Studio server place: " + code.message());
        return CopyResponse::Failed;
    }

    if (ReplaceAtomically(temporary, destination, error))
        return CopyResponse::Success;
    std::filesystem::remove(temporary, code);
    return CopyResponse::Failed;
}

// Studio reads one fixed server.rbxl path, so concurrent noobWarrior processes are serialized
// here. Nothing else in this file needs a lock: entries are content-addressed, so racing builders
// produce identical bytes and every write lands through an atomic rename.
class PublishLock {
public:
    PublishLock() {
#if defined(_WIN32)
        mMutex = CreateMutexW(nullptr, FALSE,
                              L"Local\\noobWarrior.StudioServerPlace.Publish.v1");
        if (mMutex == nullptr)
            return;
        const DWORD result = WaitForSingleObject(mMutex, kTimeoutMilliseconds);
        mLocked = result == WAIT_OBJECT_0 || result == WAIT_ABANDONED;
#else
        mLock = std::unique_lock<std::mutex>(Mutex());
        mLocked = true;
#endif
    }

    ~PublishLock() {
#if defined(_WIN32)
        if (mLocked)
            ReleaseMutex(mMutex);
        if (mMutex != nullptr)
            CloseHandle(mMutex);
#endif
    }

    bool Locked() const {
        return mLocked;
    }

private:
#if defined(_WIN32)
    // A wedged peer must not hang the launch forever; the caller reports an ordinary failure.
    static constexpr DWORD kTimeoutMilliseconds = 30000;
    HANDLE mMutex {nullptr};
#else
    static std::mutex &Mutex() {
        static std::mutex mutex;
        return mutex;
    }
    std::unique_lock<std::mutex> mLock;
#endif
    bool mLocked {false};
};

// A cache entry is a place plus its ".size" sidecar, and only the place is touched on a hit, so
// the pair is aged as one: judging the two files separately drops the sidecar of a still-hot
// entry, and an entry without its sidecar reads back as a miss (ReadExpectedSize) and is rebuilt
// on every launch from then on.
void PruneCache(const std::filesystem::path &cacheDirectory,
                const std::filesystem::path &currentEntry) {
    const auto cutoff = std::filesystem::file_time_type::clock::now() - kCacheEntryLifetime;
    std::vector<std::filesystem::path> stale;
    std::error_code code;
    std::filesystem::directory_iterator iterator(cacheDirectory, code);
    const std::filesystem::directory_iterator end;
    for (; !code && iterator != end; iterator.increment(code)) {
        const std::filesystem::directory_entry &entry = *iterator;
        if (entry.path() == currentEntry || entry.path() == SizePath(currentEntry))
            continue;
        std::error_code entryError;
        if (!entry.is_regular_file(entryError) || entryError)
            continue;
        // A sidecar leaves with the place it belongs to; one whose place is already gone ages on
        // its own timestamp so an orphan cannot outlive the cache lifetime either.
        std::filesystem::path governing = entry.path();
        if (governing.extension() == ".size") {
            std::filesystem::path place = governing;
            place.replace_extension();
            std::error_code placeError;
            if (std::filesystem::exists(place, placeError) && !placeError)
                governing = std::move(place);
        }
        const auto modified = std::filesystem::last_write_time(governing, entryError);
        if (!entryError && modified < cutoff)
            stale.push_back(entry.path());
    }
    for (const std::filesystem::path &path : stale)
        std::filesystem::remove(path, code);
}
