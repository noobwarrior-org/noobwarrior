// Parses "2013-12-09T23:53:36.957Z" into a Unix timestamp. Returns 0 on failure.
int64_t ParseIso8601(const std::string &s) {
    if (s.empty()) return 0;
    int year, mon, day, hour = 0, min = 0;
    double sec = 0;
    if (std::sscanf(s.c_str(), "%d-%d-%dT%d:%d:%lf", &year, &mon, &day, &hour, &min, &sec) < 3)
        return 0;
    std::tm tm{};
    tm.tm_year = year - 1900;
    tm.tm_mon  = mon - 1;
    tm.tm_mday = day;
    tm.tm_hour = hour;
    tm.tm_min  = min;
    tm.tm_sec  = static_cast<int>(sec);
#if defined(_WIN32)
    time_t t = _mkgmtime(&tm);
#else
    time_t t = timegm(&tm);
#endif
    return t < 0 ? 0 : static_cast<int64_t>(t);
}
