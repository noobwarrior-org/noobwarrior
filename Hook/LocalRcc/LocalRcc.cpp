static void PatchTypeForProperty() {
    if (!gTypeForPropertyImm) return;

    uint8_t byte = static_cast<uint8_t>(types::protected_string_bytecode);

    DWORD oldProtect;
    VirtualProtect(reinterpret_cast<void*>(gTypeForPropertyImm), 16,
                   PAGE_EXECUTE_READWRITE, &oldProtect);
    *reinterpret_cast<uint8_t*>(gTypeForPropertyImm) = byte;
    VirtualProtect(reinterpret_cast<void*>(gTypeForPropertyImm), 16,
                   oldProtect, &oldProtect);
}

