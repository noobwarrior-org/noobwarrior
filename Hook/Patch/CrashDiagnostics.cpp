//   VMProtect encrypts the symbols) and writing a full minidump to %TEMP%.
//
//   NOTE: the dump is MiniDumpWithFullMemory (~2 GB) and fires on ANY unhandled
//   exception (including some the player throws-and-handles), so it can fill the
//   disk -- only enable it while actively hunting a crash, and consider dropping
//   to MiniDumpNormal.
//
