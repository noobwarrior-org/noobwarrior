//   The 0.573 player crashes silently mid-session (no Roblox crash reporter, no
//   dump), and x32dbg can't attach (VMProtect anti-debug stalls the process). But
//   noobhook runs IN-process and is invisible to the anti-debug, so this captured
//   the crash from three vantage points -- an unhandled-exception filter, a
//   kernelbase!UnhandledExceptionFilter hook (the player's own top-level filter
